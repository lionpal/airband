/// A message he typed that is on its way.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize, uniffi::Record)]
pub struct Outgoing {
    pub id: String,
    pub text: String,
    /// The message it replies to, if he picked one.
    pub re: Option<String>,
    /// When he sent it, in milliseconds since 1970.
    pub at: u64,
    /// The room he was looking at when he sent it  by its team's name, if he was in one.
    #[serde(default)]
    pub scope: Option<String>,
    /// For a quick message: the words on the button. `text` is then the whole instruction.
    #[serde(default)]
    pub label: Option<String>,
    /// Files that go with it, by the ids they reached the tower under.
    #[serde(default)]
    pub attachments: Vec<String>,
    /// For the tower, not for a host to read: the agents on his screen that other computers have, as JSON.
    #[serde(default)]
    pub others: String,
    /// The agents he picked for it on his screen, by id.
    #[serde(default)]
    pub to: Vec<String>,
    /// For the tower, not for a host to read: what a button of his stood for, as JSON. Empty for words.
    #[serde(default)]
    pub act: String,
    /// The question of his computer's this answers, by its id: set when it is the next thing he said after
    /// the computer asked him something back.
    #[serde(default)]
    pub answers: Option<String>,
    /// How many times it has been tried.
    #[serde(default)]
    pub tries: u32,
    /// When it was last tried, in milliseconds since 1970; 0 before the first try.
    #[serde(default)]
    pub last_tried: u64,
    /// How the last try went, a sentence for each way it was tried ("The relay says your computer is not
    /// connected."). Empty before the first try, and while nothing has gone wrong. Kept on this device only.
    #[serde(default)]
    pub trail: Vec<String>,
    /// It is no longer being tried, and why, in a sentence: it could not be sent, or half an hour of trying
    /// was not enough. It stays in the list until he sends it again ([`Radio::send_again`]) or lets it go
    /// ([`Radio::discard`]).
    #[serde(default)]
    pub failed: Option<String>,
    /// How far it has got.
    #[serde(default)]
    pub stage: Stage,
}

/// What an agent is doing.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, uniffi::Enum)]
pub enum AgentState {
    Working,
    /// It has a question open for him.
    Asking,
    /// It stopped without finishing or asking: a poke sets it going again.
    Stalled,
    /// It finished and reported.
    Idle,
    /// His computer did not say, or said something this build does not know.
    #[default]
    Unknown,
}
impl From<airband_core::radio::AgentState> for AgentState {
    fn from(s: airband_core::radio::AgentState) -> Self {
        use airband_core::radio::AgentState as S;
        match s {
            S::Working => Self::Working,
            S::Asking => Self::Asking,
            S::Stalled => Self::Stalled,
            S::Idle => Self::Idle,
            S::Unknown => Self::Unknown,
        }
    }
}

/// How far something he typed has got on its way.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize, uniffi::Enum)]
pub enum Stage {
    /// It has not reached his computer or the relay yet.
    #[default]
    Trying,
    /// His computer has it and is working out who it is for. It leaves the list when that is done.
    Taken,
    /// The relay is keeping it for his computer, which is away or still catching up.
    Left,
}

impl Outgoing {
    /// Something he has just said, not yet tried.
    pub(crate) fn new(id: String, text: String, re: Option<String>, scope: Option<String>, label: Option<String>, attachments: Vec<String>, others: String) -> Outgoing {
        Outgoing { id, text, re, at: now_ms(), scope, label, attachments, others, to: Vec::new(), act: String::new(), answers: None, tries: 0, last_tried: 0, trail: Vec::new(), failed: None, stage: Stage::Trying }
    }
    /// Words to send, under a new id, with nothing else yet: the rest is set by whoever sends them.
    pub(crate) fn of(text: String) -> Outgoing {
        Outgoing::new(random_hex(12), text, None, None, None, Vec::new(), String::new())
    }
    /// What a button of his stood for goes with it, kept as the tower will read it.
    pub(crate) fn with_act(self, act: Option<&Act>) -> Outgoing {
        Outgoing { act: act.and_then(|a| serde_json::to_string(a).ok()).unwrap_or_default(), ..self }
    }
    /// What the tower is sent for it: the one place an utterance is made from something he said. None when
    /// what was kept with it (a button's act, who else is on his screen) no longer reads: it is then never
    /// sent as plain words in its place.
    pub(crate) fn utterance(&self) -> Option<Utterance> {
        let act = if self.act.is_empty() { None } else { Some(serde_json::from_str(&self.act).ok()?) };
        let others = if self.others.is_empty() { Vec::new() } else { serde_json::from_str(&self.others).ok()? };
        Some(Utterance { text: self.text.clone(), id: self.id.clone(), re: self.re.clone(), scope: self.scope.clone(), label: self.label.clone(), attachments: self.attachments.clone(), others, to: self.to.clone(), act, answers: self.answers.clone() })
    }
}

#[derive(Debug, uniffi::Error)]
pub enum RadioError {
    BadLink { reason: String },
    /// Nothing came back: no network, no relay, or the tower is not running.
    Offline,
    /// The tower answered and said no.
    Refused,
    /// The tower answered, said no, and said why in words for him.
    Told { reason: String },
    /// It did not go now, and is kept on this phone and sent when it can be: why, and that, in words for him.
    Kept { reason: String },
}

impl RadioError {
    /// Something on this phone itself failed (a file it could not read or keep): said as that, never as his
    /// computer refusing.
    pub(crate) fn here(what: &str) -> RadioError {
        RadioError::Told { reason: format!("This phone could not {what}.") }
    }
}

/// An address with its query, each value encoded: the one way an address with a query is put together, for
/// a service and for the tower alike.
pub(crate) fn with_query(base: &str, pairs: &[(&str, &str)]) -> String {
    let mut q = url::form_urlencoded::Serializer::new(String::new());
    q.extend_pairs(pairs);
    format!("{base}?{}", q.finish())
}

/// A tower that speaks another version of the radio protocol is told apart from one that cannot be reached:
/// he is asked to update, not left looking at a chat that half works. One that says no version is not taken
/// to speak this one.
fn spoken_alike(feed: &Feed) -> Result<(), RadioError> {
    if feed.schema == airband_core::radio::SCHEMA {
        return Ok(());
    }
    Err(RadioError::Told { reason: "This computer runs another version of airband. Update it and this app.".into() })
}

impl std::fmt::Display for RadioError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            RadioError::BadLink { reason } => write!(f, "{reason}"),
            RadioError::Offline => write!(f, "cannot reach your computer"),
            RadioError::Refused => write!(f, "your computer refused that"),
            RadioError::Told { reason } | RadioError::Kept { reason } => write!(f, "{reason}"),
        }
    }
}

impl From<LinkError> for RadioError {
    fn from(e: LinkError) -> Self {
        match e {
            // his computer's own reason, when it gave one, is what he should read
            LinkError::Tower { error, .. } if !error.is_empty() => RadioError::Told { reason: error },
            // trouble of its own, which may pass, is not a no
            e @ LinkError::Tower { status: 500..=599, .. } => RadioError::Told { reason: e.said() },
            LinkError::Tower { .. } => RadioError::Refused,
            // it will not go however often it is tried: he is told why, never that it goes when it can
            e if e.retry() == Retry::Never => RadioError::Told { reason: e.said() },
            _ => RadioError::Offline,
        }
    }
}

/// Does the phone's core have the code for what this offer names? Speaking and listening are this device's
/// own; reading is his computer's, so nothing here stands in the way of a summary offer. The one rule, for
/// the catalogue this device keeps and for whoever checks a catalogue before it is published.
pub fn can_use(offer: &airband_core::providers::Offer) -> bool {
    match offer.job {
        airband_core::providers::Job::Voice => voices::speaks(offer),
        airband_core::providers::Job::Ears => hears::listens(offer),
        airband_core::providers::Job::Summary => true,
    }
}
