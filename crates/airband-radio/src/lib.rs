pub(crate) struct Senses {
    pub(crate) mouth: mouth::Mouth,
    pub(crate) ears: ears::Chosen,
    pub(crate) passes: ears::Passes,
    pub(crate) takes: takes::Takes,
}

#[derive(Debug, Clone, PartialEq, Eq, uniffi::Enum)]
pub enum RadioStatus {
    /// Cannot reach the tower; retrying.
    Offline,
    /// Connected, nothing happening.
    Idle,
    /// Speaking what this agent said (its id, and what it is called), or with nobody named, airband's own words.
    Speaking { agent: Option<String>, callsign: Option<String> },
    /// The microphone is open.
    Listening,
    /// Sending what was said.
    Sending,
}

/// What a radio's host provides: the desk, for each computer on a phone, or a terminal. Calls arrive on the
/// radio's own thread, one at a time, and may block. An app never implements it; it talks to the desk.
pub trait RadioHost: Send + Sync {
    /// Show this, for a radio started on its own ([`Radio::start`]: a terminal, which prints); return when it
    /// has. Never asked of a phone, where what speaks is what he chose in the app.
    fn speak(&self, text: String);
    /// Take a line he types, for a radio started on its own (a terminal), or nothing if he gave none. Never
    /// asked of a phone, where what listens is what he chose in the app.
    fn listen(&self) -> Option<String>;
    /// For the screen.
    fn status(&self, status: RadioStatus);
    /// Play 16-bit little-endian mono PCM at `rate` samples a second, queued after anything already playing.
    /// Returns at once, except with `last`: then it returns when everything queued has been heard. May be
    /// called with no audio and `last` to wait for what is already queued.
    fn play(&self, rate: u32, pcm: Vec<u8>, last: bool);
    /// Start capturing the microphone as 16-bit little-endian mono PCM at `rate`. False if this host cannot,
    /// in which case `listen` is used.
    fn record_start(&self, rate: u32) -> bool;
    /// The next captured audio, about a tenth of a second of it. Blocks until there is some. Empty once the
    /// microphone has been stopped.
    fn record_read(&self) -> Vec<u8>;
    fn record_stop(&self);
    /// His typed messages that have not reached the tower yet, oldest first, each time that changes. `note`
    /// is something he must be told about one of them (it could not be placed, or it expired unsent).
    fn outbox(&self, waiting: Vec<Outgoing>, note: Option<String>);
    /// What he has said so far, while he is still speaking: the whole of it each time, revised as the service
    /// hears more. For showing; what is sent is what the listening returns.
    fn hearing(&self, text: String);
    /// What the voice is saying in the clip now starting to play, and when each word of it is said: where each
    /// word starts in `text` (in characters) and how many milliseconds into the clip. Called again, with empty
    /// `text`, as more of a long clip's timings arrive. For showing the words as they are spoken; a clip with no
    /// timings is not announced at all.
    fn words(&self, text: String, starts: Vec<u32>, at_ms: Vec<u32>);
    /// Run a model with an engine the host has. `engine` is the name the model's row gives, `folder` is where
    /// the model's files are. For listening `input` is a recording (16-bit little-endian mono PCM at 16 kHz)
    /// and the answer is the words, as UTF-8. For a voice it is JSON, `{"text": the words, "voice": the
    /// voice's name}`, and the answer is the sound (16-bit little-endian mono PCM at the rate the row
    /// gives). Nothing when the host cannot: it has no such engine, or the model would not load. Blocks while
    /// it works.
    fn run_model(&self, engine: String, folder: String, job: ChoiceJob, input: Vec<u8>) -> Option<Vec<u8>>;
    /// Something he chose on this device (what listens, what speaks) could not do its job just now, and why.
    /// It stays chosen. A host with a screen says so; one without need not.
    fn told(&self, text: String);
    /// The tower did not deliver this message of his. Either it is for an agent another of his computers has
    /// (`elsewhere`, its id), or the tower could not tell who it is for (`ask`: who it might be by id, likeliest
    /// first). A host with a screen offers the choice; nothing more is sent until he makes it.
    fn unplaced(&self, message: Outgoing, elsewhere: Option<String>, ask: Vec<String>);
}

/// What came of opening the microphone.
pub(crate) enum Listened {
    /// His words, and the take they were heard from: its id is the id the message made of them goes under.
    /// Nothing for a line typed in a terminal, which has no recording.
    Said { text: String, take: Option<String> },
    /// He said nothing.
    Nothing,
    /// There is nothing to listen with: nothing is chosen, what he chose cannot be used, or the microphone
    /// would not open. Nothing was recorded.
    Cannot,
    /// What listened did not hear it. The take keeps the whole recording, and the chat shows it to him.
    Unheard { take: String },
}

/// A message he typed that is on its way, as it is kept on the device and sent. A host sees it as a
/// [`desk::DeskOutgoing`].
#[derive(Clone, serde::Serialize, serde::Deserialize)]
pub struct Outgoing {
    pub id: String,
    pub text: String,
    /// The message it replies to, if he picked one.
    pub re: Option<String>,
    /// When he sent it, in milliseconds since 1970.
    pub at: u64,
    /// The team of the room he was looking at when he sent it, by the team's id, if he was in one.
    #[serde(default)]
    pub scope: Option<String>,
    /// For a quick message: the words on the button. `text` is then the whole instruction.
    #[serde(default)]
    pub label: Option<String>,
    /// Files that go with it, by the ids they reached the tower under.
    #[serde(default)]
    pub attachments: Vec<String>,
    /// The agents on his screen that other computers have, for the tower to know who else he could mean.
    #[serde(default)]
    pub others: Vec<airband_core::radio::Other>,
    /// The agents he picked for it on his screen, by id.
    #[serde(default)]
    pub to: Vec<String>,
    /// What a button of his stood for. Nothing for words.
    #[serde(default)]
    pub act: Option<Act>,
    /// The question of his computer's this answers, by its id: set when it is the next thing he said after
    /// the computer asked him something back.
    #[serde(default)]
    pub answers: Option<String>,
    /// How many times it has been tried.
    #[serde(default)]
    pub tries: u32,
    /// When it was last tried, in milliseconds since 1970; 0 before the first try.
    #[serde(default)]
    pub last_tried: u64,
    /// How the last try went, a sentence for each way it was tried ("The relay says your computer is not
    /// connected."). Empty before the first try, and while nothing has gone wrong. Kept on this device only.
    #[serde(default)]
    pub trail: Vec<String>,
    /// It is no longer being tried, and why, in a sentence: it could not be sent, or half an hour of trying
    /// was not enough. It stays in the list until he sends it again ([`Radio::send_again`]) or lets it go
    /// ([`Radio::discard`]).
    #[serde(default)]
    pub failed: Option<String>,
    /// How far it has got.
    #[serde(default)]
    pub stage: Stage,
    /// When his computer first said it had it ([`Stage::Taken`]), in milliseconds since 1970: what the outbox's
    /// patience with a message his computer has and never settles is counted from. Nothing before then.
    #[serde(default)]
    pub taken_at: Option<u64>,
}

/// What an agent is doing.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, uniffi::Enum)]
pub enum AgentState {
    Working,
    /// It has a question open for him.
    Asking,
    /// It stopped without finishing or asking: a poke sets it going again.
    Stalled,
    /// It finished and reported.
    Idle,
    /// His computer did not say, or said something this build does not know.
    #[default]
    Unknown,
}
impl From<airband_core::radio::AgentState> for AgentState {
    fn from(s: airband_core::radio::AgentState) -> Self {
        use airband_core::radio::AgentState as S;
        match s {
            S::Working => Self::Working,
            S::Asking => Self::Asking,
            S::Stalled => Self::Stalled,
            S::Idle => Self::Idle,
            S::Unknown => Self::Unknown,
        }
    }
}

/// How far something he typed has got on its way.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize, uniffi::Enum)]
pub enum Stage {
    /// It has not reached his computer or the relay yet.
    #[default]
    Trying,
    /// His computer has it and is working out who it is for. It leaves the list when that is done.
    Taken,
    /// The relay is keeping it for his computer, which is away or still catching up.
    Left,
}

impl Outgoing {
    /// Something he has just said, not yet tried.
    pub(crate) fn new(id: String, text: String, re: Option<String>, scope: Option<String>, label: Option<String>, attachments: Vec<String>, others: Vec<airband_core::radio::Other>) -> Outgoing {
        Outgoing { id, text, re, at: now_ms(), scope, label, attachments, others, to: Vec::new(), act: None, answers: None, tries: 0, last_tried: 0, trail: Vec::new(), failed: None, stage: Stage::Trying, taken_at: None }
    }
    /// Words to send, under a new id, with nothing else yet: the rest is set by whoever sends them.
    pub(crate) fn of(text: String) -> Outgoing {
        Outgoing::new(random_hex(12), text, None, None, None, Vec::new(), Vec::new())
    }
    /// What a button of his stood for goes with it.
    pub(crate) fn with_act(self, act: Option<&Act>) -> Outgoing {
        Outgoing { act: act.cloned(), ..self }
    }
    /// What it shows as, and is quoted as to him: a quick message's button words, or what he typed.
    pub(crate) fn shown(&self) -> String {
        self.label.clone().unwrap_or_else(|| self.text.clone())
    }
    /// What the tower is sent for it: the one place an utterance is made from something he said.
    pub(crate) fn utterance(&self) -> Utterance {
        Utterance { text: self.text.clone(), id: self.id.clone(), re: self.re.clone(), scope: self.scope.clone(), label: self.label.clone(), attachments: self.attachments.clone(), others: self.others.clone(), to: self.to.clone(), act: self.act.clone(), answers: self.answers.clone().map(airband_core::ids::QuestionId::new) }
    }
}

/// His words and an agent's are never printed: what is printed of each is its id and how long its words are.
/// Everything else about them is in the type.
macro_rules! words_hidden {
    ($t:ty, $name:literal, $id:ident, $($words:ident),+) => {
        impl std::fmt::Debug for $t {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                let mut d = f.debug_struct($name);
                d.field(stringify!($id), &self.$id);
                $(d.field(stringify!($words), &format_args!("{} characters", self.$words.chars().count()));)+
                d.finish_non_exhaustive()
            }
        }
    };
}
words_hidden!(Outgoing, "Outgoing", id, text);
words_hidden!(chat::ChatMessage, "ChatMessage", id, text);
words_hidden!(desk::OpenedNotice, "OpenedNotice", message, title, body);
words_hidden!(desk::DeskOutgoing, "DeskOutgoing", id, shown);

#[derive(Debug, PartialEq, uniffi::Error)]
pub enum RadioError {
    BadLink { reason: String },
    /// Nothing came back: no network, no relay, or the tower is not running.
    Offline,
    /// The tower answered, said no, and said why in words for him.
    Told { reason: String },
    /// His computer or the relay had trouble that may pass, with why in words for him: not a no. It is tried
    /// again later.
    Trouble { reason: String },
}

impl RadioError {
    /// What it is, in words for him.
    pub(crate) fn said(&self) -> String {
        match self {
            RadioError::BadLink { reason } | RadioError::Told { reason } | RadioError::Trouble { reason } => reason.clone(),
            RadioError::Offline => UNREACHED.into(),
        }
    }
    /// What he asked about is not on any of his computers as this phone last saw them (a message, an agent):
    /// said as that, never as his computer refusing.
    pub(crate) fn gone(what: &str) -> RadioError {
        crate::choices::told(format!("That {what} is no longer on any of your computers."))
    }
    /// Something on this phone itself failed (a file it could not read or keep): said as that, never as his
    /// computer refusing.
    pub(crate) fn here(what: &str) -> RadioError {
        crate::choices::told(format!("This phone could not {what}."))
    }
}

/// An address of a service with its query, each value encoded. The tower's own addresses are made by core
/// ([`airband_core::radio::wire::address`]).
pub(crate) fn with_query(base: &str, pairs: &[(&str, &str)]) -> String {
    let mut q = url::form_urlencoded::Serializer::new(String::new());
    q.extend_pairs(pairs);
    format!("{base}?{}", q.finish())
}

/// What he is told when his computer could not be reached: the one wording, on the screen
/// ([`DeskView::cannot_reach`]) and for any request that got no answer.
pub(crate) const UNREACHED: &str = "Can\u{2019}t reach your computer.";

/// What went wrong, in words for him: the one wording the screens show for any of the core's errors.
#[uniffi::export]
pub fn error_words(error: RadioError) -> String {
    error.said()
}

impl std::fmt::Display for RadioError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        // the one wording, [`RadioError::said`]
        write!(f, "{}", self.said())
    }
}

/// The one reading of a failed request for him. What may work in a moment is told as nothing coming back;
/// trouble that may pass (his computer's 5xx, its "not now", the relay's limits) as trouble, never as a no; a
/// refusal with its own words. Each by its kind, never its words.
impl From<LinkError> for RadioError {
    fn from(e: LinkError) -> Self {
        match e.retry() {
            Retry::Soon => RadioError::Offline,
            Retry::Later => match e {
                // not now, with its reason: it may work later
                LinkError::Refused(airband_core::radio::wire::Refusal::NotNow { reason }) => RadioError::Trouble { reason },
                e => RadioError::Trouble { reason: e.said() },
            },
            Retry::Never => match e {
                // his computer's own reason, when it gave one, is what he should read
                LinkError::Refused(r) if r.reason().is_some() => RadioError::Told { reason: r.reason().unwrap_or_default().to_string() },
                // anything else it will not do, or that will never go: said by its kind
                e => RadioError::Told { reason: e.said() },
            },
        }
    }
}

/// Does the phone's core have the code for what this offer names? Speaking and listening are this device's
/// own; reading is his computer's, so nothing here stands in the way of a summary offer. The one rule, for
/// the catalogue this device keeps and for whoever checks a catalogue before it is published.
pub fn can_use(offer: &airband_core::providers::Offer) -> bool {
    match offer.job {
        airband_core::providers::Job::Voice => voices::speaks(offer),
        airband_core::providers::Job::Ears => hears::listens(offer),
        airband_core::providers::Job::Summary => true,
    }
}
