/// What the radio's waiting threads sleep on: they are woken when there is something to do (a message to send,
/// a call starting, stopping), and do not wake up several times a second to look.
#[derive(Default)]
pub(crate) struct Wake {
    turn: Mutex<u64>,
    rung: std::sync::Condvar,
}

impl Wake {
    pub(crate) fn ring(&self) {
        *self.turn.lock().unwrap() += 1;
        self.rung.notify_all();
    }
    /// Sleep until rung, or for `at_most`.
    pub(crate) fn wait(&self, at_most: Duration) {
        let turn = self.turn.lock().unwrap();
        let was = *turn;
        let _ = self.rung.wait_timeout_while(turn, at_most, |now| *now == was);
    }
}

#[derive(uniffi::Object)]
pub struct Radio {
    jobs: Mutex<Sender<Job>>,
    stop: Arc<AtomicBool>,
    calling: Arc<AtomicBool>,
    link: Arc<Link>,
    store: Arc<Store>,
    host: Arc<dyn RadioHost>,
    wake: Arc<Wake>,
    /// The roster as last seen, by the tower's number for it: sent back so a wait also ends when it changes.
    roster: std::sync::atomic::AtomicU64,
    /// Goes up each time a reading aloud is started or stopped: one that finds it changed leaves off.
    reading: std::sync::atomic::AtomicU64,
}

#[uniffi::export]
impl Radio {
    /// Start working with the tower this pairing link leads to (the link `airband pair` prints). Returns at
    /// once; fails only if the link is not a pairing link. `data_dir` is a folder of the app's own where
    /// unsent messages and the recent chat are kept across restarts; empty keeps nothing.
    #[uniffi::constructor]
    pub fn start(link: String, data_dir: String, host: Arc<dyn RadioHost>) -> Result<Arc<Self>, RadioError> {
        let store = Arc::new(Store::open(&data_dir));
        let me = store.saved.lock().unwrap().radio.clone();
        let me = if me.is_empty() { store.change(|s| { s.radio = format!("radio-{}", random_hex(4)); s.radio.clone() }) } else { me };
        let link = Pairing::parse(&link).and_then(|p| Link::new(p, &me)).map_err(|reason| RadioError::BadLink { reason })?;
        let (tx, rx) = channel();
        let stop = Arc::new(AtomicBool::new(false));
        let link = Arc::new(link);
        let busy = Arc::new(AtomicBool::new(false));
        let calling = Arc::new(AtomicBool::new(false));
        let wake = Arc::new(Wake::default());
        {
            let (link, host, stop, busy) = (link.clone(), host.clone(), stop.clone(), busy.clone());
            thread::spawn(move || work(rx, link, host, stop, busy));
        }
        {
            let (tx, stop, link, calling, host, wake) = (tx.clone(), stop.clone(), link.clone(), calling.clone(), host.clone(), wake.clone());
            thread::spawn(move || poll(tx, link, host, stop, busy, calling, wake));
        }
        store.prune_pictures();
        {
            let (link, store, host, stop, wake) = (link.clone(), store.clone(), host.clone(), stop.clone(), wake.clone());
            thread::spawn(move || deliver_outbox(link, store, host, stop, wake));
        }
        Ok(Arc::new(Radio { jobs: Mutex::new(tx), stop, calling, link, store, host, wake, roster: std::sync::atomic::AtomicU64::new(0), reading: std::sync::atomic::AtomicU64::new(0) }))
    }

    /// Chat, for a bad connection: take what he typed and keep trying until the tower has it. Returns at
    /// once. The host hears about progress through `outbox`. Survives the app closing; gives up, and says
    /// so, after half an hour.
    ///
    /// Who it is for: tags at the start of the text if there are any; else the message `re` if he picked one;
    /// else the tower works it out from what he wrote, among the agents in `scope` (`group:<name>` for one
    /// project's room; nothing for all of them).
    /// `label`, for a quick message, is the button's words: the chat shows those and the agent gets `text`.
    pub fn queue(&self, text: String, re: Option<String>, scope: Option<String>, label: Option<String>) {
        self.queue_with(text, re, scope, label, String::new());
    }
}

impl Radio {
    /// A request whose answer is nothing or a reason in words.
    fn ask(&self, path: &str, body: Value) -> Result<(), RadioError> {
        let (status, v) = self.link.request("POST", path, Some(body))?;
        match (status, v["error"].as_str()) {
            (200, Some(why)) => Err(RadioError::Told { reason: why.into() }),
            (200, None) => Ok(()),
            (404, _) => Err(RadioError::Told { reason: "Update airband on this computer first.".into() }),
            _ => Err(RadioError::Refused),
        }
    }

    /// Read a whole message aloud in the tower's voice. Blocks until it has been heard or [`Radio::hush`] is
    /// called. False when the tower has no voice to read it with.
    pub(crate) fn read_aloud(&self, id: &str) -> bool {
        let mine = self.reading.fetch_add(1, Ordering::SeqCst) + 1;
        let speech = match self.link.request("GET", &format!("/message/{id}?form=speech"), None) {
            Ok((200, v)) => v["speech"].as_str().map(String::from),
            _ => None,
        };
        speech.is_some_and(|speech| voice::play(&self.link, &*self.host, &speech, &|| self.reading.load(Ordering::SeqCst) != mine))
    }
    /// Leave off reading aloud.
    pub(crate) fn hush(&self) {
        self.reading.fetch_add(1, Ordering::SeqCst);
    }

    /// He opened the microphone himself: listen until the host closes it and hand over what he said. Nothing
    /// is sent; the caller decides where it goes.
    pub(crate) fn dictate(&self, done: Box<dyn FnOnce(Listened) + Send>) {
        let _ = self.jobs.lock().unwrap().send(Job::Dictate(done));
    }

    /// As [`Radio::queue`], with the agents on his screen that other computers have (JSON, for the tower).
    pub(crate) fn queue_with(&self, text: String, re: Option<String>, scope: Option<String>, label: Option<String>, others: String) {
        let waiting = self.store.change(|s| {
            // whatever he attached and has reached the tower goes with this
            s.outbox.push(Outgoing { id: random_hex(12), text, re, at: now_ms(), scope, label, attachments: self.link.take_armed(), others });
            s.outbox.clone()
        });
        self.wake.ring();
        self.host.outbox(waiting, None);
    }

    /// A file he attached has reached the tower: the next thing he says or sends from this radio takes it along.
    pub fn arm(&self, id: String) {
        self.link.arm(id);
    }
    /// He took it off again before sending.
    pub fn disarm(&self, id: String) {
        self.link.disarm(&id);
    }
    /// The attached files still waiting for something to go with.
    pub fn armed(&self) -> Vec<String> {
        self.link.armed()
    }

    /// The recent chat as last seen, from the device: there at once, with or without a connection.
    pub fn history(&self) -> Vec<ChatMessage> {
        self.store.saved.lock().unwrap().history.iter().cloned().map(chat).collect()
    }

    /// Chat: wait up to `wait_seconds` for anything new since the last call, across all agents, and return
    /// it. Keeps its own place, on the device, so nothing is fetched twice or missed between launches.
    /// Blocks: call it in a loop off the main thread.
    pub fn follow(&self, wait_seconds: u32) -> Result<ChatFeed, RadioError> {
        let (after, since) = {
            let saved = self.store.saved.lock().unwrap();
            (saved.after, saved.rev)
        };
        // `since` is what a current tower answers; `after` is there for one from before change counts
        let roster = self.roster.load(Ordering::SeqCst);
        let (status, v) = self.link.request("GET", &format!("/feed?scope=all&since={since}&after={after}&roster={roster}&wait={}", wait_seconds.min(25)), None)?;
        let feed: Feed = (status == 200).then(|| serde_json::from_value(v).ok()).flatten().ok_or(RadioError::Refused)?;
        self.roster.store(feed.roster_rev, Ordering::SeqCst);
        self.link.set_direct(feed.direct.clone());
        // the tower's log is behind ours: it was reset. Start over rather than wait for numbers that will not come.
        let reset = feed.seq < after || feed.rev < since;
        self.store.change(|s| {
            if reset {
                s.history.clear();
                s.after = 0;
            }
            // after a reset this answer held nothing (it was asked for changes since a count the tower has not
            // reached): ask again from the start, and the newest lines come at once
            s.rev = if reset { 0 } else { feed.rev };
            s.after = feed.messages.iter().map(|m| m.seq).max().unwrap_or(s.after).max(s.after);
            // a line seen before is replaced by its current form: its short version was made, or its sender renamed
            for m in &feed.messages {
                match s.history.iter_mut().find(|h| h.id == m.id) {
                    Some(have) => *have = m.clone(),
                    None => s.history.push(m.clone()),
                }
            }
            s.history.sort_by_key(|m| m.seq);
            let extra = s.history.len().saturating_sub(HISTORY_KEEP);
            s.history.drain(..extra);
        });
        Ok(chat_feed(feed))
    }

    /// Call mode: transmissions are spoken one at a time and the microphone opens after each. Off by
    /// default; with it off the radio is silent and only the chat calls below do anything.
    pub fn set_call_mode(&self, on: bool) {
        self.calling.store(on, Ordering::SeqCst);
        self.wake.ring();
    }

    /// Chat: everything said since `after` in a scope ("all", "group:shop", "agent:shop two"), each message
    /// cut to a line or two. Waits up to `wait_seconds` (25 at most) for something new. Blocks: call it off
    /// the main thread.
    pub fn feed(&self, scope: String, after: u64, wait_seconds: u32) -> Result<ChatFeed, RadioError> {
        let scope: String = scope.bytes().map(|b| if b.is_ascii_alphanumeric() || b == b':' { (b as char).to_string() } else { format!("%{b:02X}") }).collect();
        let (status, v) = self.link.request("GET", &format!("/feed?scope={scope}&after={after}&wait={}", wait_seconds.min(25)), None)?;
        let feed: Feed = (status == 200).then(|| serde_json::from_value(v).ok()).flatten().ok_or(RadioError::Refused)?;
        self.link.set_direct(feed.direct.clone());
        Ok(chat_feed(feed))
    }

    /// Chat: send what he typed. Leading tags say who it is for: "@shop2 leave them", "@shop stop", "@all".
    /// With no tag it goes to whoever spoke last. Returns the tower's one-line answer ("Sent to shop two.").
    /// `re` is the id of the message he is replying to, when he picked one.
    pub fn send(&self, text: String, re: Option<String>) -> Result<String, RadioError> {
        Ok(self.link.utterance(&text, re, None)?.say)
    }

    /// The rest of a message: the fuller spoken version, or with `full` exactly what the agent wrote.
    pub fn more(&self, id: String, full: bool) -> Result<String, RadioError> {
        let (status, v) = self.link.request("GET", &format!("/message/{id}?form={}", if full { "full" } else { "detail" }), None)?;
        (status == 200).then(|| v["text"].as_str().map(String::from)).flatten().ok_or(RadioError::Refused)
    }

    /// The accounts the agents on this computer can run under, and how much of each is used. `fresh` asks the
    /// tower to check again now. Blocks: call it off the main thread.
    pub fn accounts(&self, station: String, fresh: bool) -> Result<StationAccounts, RadioError> {
        let (status, v) = self.link.request("GET", if fresh { "/accounts?fresh=1" } else { "/accounts" }, None)?;
        match status {
            200 => serde_json::from_value(v).map(|a| StationAccounts::from(&station, a)).map_err(|_| RadioError::Refused),
            404 => Err(RadioError::Told { reason: "Update airband on this computer to see its accounts.".into() }),
            _ => Err(RadioError::Refused),
        }
    }

    /// Move this computer's sessions of one harness to another account. Returns how things stand afterwards.
    /// Blocks: call it off the main thread.
    pub fn use_account(&self, station: String, harness: String, id: String) -> Result<StationAccounts, RadioError> {
        let (status, v) = self.link.request("POST", "/accounts/use", Some(serde_json::json!({ "harness": harness, "id": id })))?;
        match (status, v["error"].as_str()) {
            (200, Some(why)) => Err(RadioError::Told { reason: why.into() }),
            (200, None) => serde_json::from_value(v).map(|a| StationAccounts::from(&station, a)).map_err(|_| RadioError::Refused),
            _ => Err(RadioError::Refused),
        }
    }

    /// Put an agent in another team: one that exists, or a new one of that name. Returns what the agent is
    /// called now and the team it is in. Blocks: call it off the main thread.
    pub fn move_agent(&self, agent: String, team: String) -> Result<Vec<String>, RadioError> {
        let (status, v) = self.link.request("POST", "/team", Some(serde_json::json!({ "agent": agent, "team": team })))?;
        match (status, v["error"].as_str(), v["callsign"].as_str(), v["team"].as_str()) {
            (200, Some(why), _, _) => Err(RadioError::Told { reason: why.into() }),
            (200, None, Some(callsign), Some(team)) => Ok(vec![callsign.to_string(), team.to_string()]),
            (404, _, _, _) => Err(RadioError::Told { reason: "Update airband on this computer to move its agents.".into() }),
            _ => Err(RadioError::Refused),
        }
    }

    /// Stop what an agent the tower runs is doing, now. Blocks: call it off the main thread.
    pub fn stop_agent(&self, agent: String) -> Result<(), RadioError> {
        self.ask("/stop", serde_json::json!({ "agent": agent }))
    }
    /// End an agent the tower runs. Blocks: call it off the main thread.
    pub fn end_agent(&self, agent: String) -> Result<(), RadioError> {
        self.ask("/end", serde_json::json!({ "agent": agent }))
    }
    /// Take back something he said that is still waiting its turn. Blocks: call it off the main thread.
    pub fn unsend(&self, message: String) -> Result<(), RadioError> {
        self.ask("/unsend", serde_json::json!({ "message": message }))
    }

    /// Have the tower take over an agent he started in a terminal: that session ends there and carries on in a
    /// process the tower holds. Blocks: call it off the main thread.
    pub fn take_over(&self, agent: String) -> Result<(), RadioError> {
        let (status, v) = self.link.request("POST", "/takeover", Some(serde_json::json!({ "agent": agent })))?;
        match (status, v["error"].as_str()) {
            (200, Some(why)) => Err(RadioError::Told { reason: why.into() }),
            (200, None) => Ok(()),
            (404, _) => Err(RadioError::Told { reason: "Update airband on this computer first.".into() }),
            _ => Err(RadioError::Refused),
        }
    }

    /// A picture, as a JPEG file on the device: fetched from the tower the first time and kept, so it is there
    /// at once afterwards and without a connection. Returns the file's path. Blocks: call it off the main thread.
    pub fn picture(&self, id: String) -> Result<String, RadioError> {
        if id.is_empty() || !id.bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err(RadioError::Refused);
        }
        let file = self.store.pictures().join(format!("{id}.jpg"));
        if file.is_file() {
            return Ok(file.display().to_string());
        }
        let (mut bytes, mut from) = (Vec::new(), 0u32);
        loop {
            let (status, v) = self.link.request("GET", &format!("/picture/{id}?from={from}"), None)?;
            let part: airband_core::radio::PicturePart = (status == 200).then(|| serde_json::from_value(v).ok()).flatten().ok_or(RadioError::Refused)?;
            bytes.extend(airband_core::audio::base64_decode(&part.data).ok_or(RadioError::Refused)?);
            // a part that moves nothing forward would loop for ever
            if part.done || part.next <= from {
                break;
            }
            from = part.next;
        }
        let tmp = file.with_extension(format!("{}.tmp", random_hex(4)));
        std::fs::create_dir_all(file.parent().unwrap()).and_then(|_| std::fs::write(&tmp, &bytes)).and_then(|_| std::fs::rename(&tmp, &file)).map_err(|_| RadioError::Refused)?;
        Ok(file.display().to_string())
    }

    /// He has read these in the chat, so call mode will not also read them out.
    pub fn seen(&self, ids: Vec<String>) {
        for id in ids {
            let _ = self.link.post("/heard", &Heard { id });
        }
    }

    /// He wants to say something unprompted (a button, Siri, a shortcut): open the microphone when free. `re` is
    /// the id of the message he means to answer, when he picked one; without it the tower works out who it is for.
    /// `scope` is the room he is looking at (`group:<name>`), which narrows that; nothing for all agents.
    pub fn talk(&self, re: Option<String>, scope: Option<String>) {
        let _ = self.jobs.lock().unwrap().send(Job::Talk(re, scope));
    }

    /// Stop for good. A transmission already being spoken finishes.
    pub fn stop(&self) {
        self.stop.store(true, Ordering::SeqCst);
        self.wake.ring();
    }
}

impl Drop for Radio {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::SeqCst);
        self.wake.ring();
    }
}

impl Radio {
    /// Send a file to the tower in parts, under `id`. `sent` is told how far it has got after each part and
    /// returns false to give up. Blocks until it is all there, the tower refuses it, or it is given up on.
    pub(crate) fn upload(&self, id: &str, path: &str, name: &str, mut sent: impl FnMut(u64, u64) -> bool) -> Result<(), RadioError> {
        use std::io::{Read, Seek, SeekFrom};
        // 90 KB of file is 120 KB of text, which fits one sealed message through a relay
        const PART: u64 = 90_000;
        // Every part is a round trip to his computer and back, so they go several at once: a video is hundreds
        // of them. The first goes alone, to learn whether the tower takes parts in any order; an older one
        // does not, and gets them one after another.
        const AT_ONCE: usize = 6;
        let total = std::fs::metadata(path).map_err(|_| RadioError::Refused)?.len();
        let part_at = |from: u64, with_total: bool| -> Result<airband_core::radio::AttachmentPart, RadioError> {
            let mut file = std::fs::File::open(path).map_err(|_| RadioError::Refused)?;
            file.seek(SeekFrom::Start(from)).map_err(|_| RadioError::Refused)?;
            let mut buf = Vec::with_capacity(PART as usize);
            file.take(PART).read_to_end(&mut buf).map_err(|_| RadioError::Refused)?;
            let done = from + buf.len() as u64 >= total;
            Ok(airband_core::radio::AttachmentPart { id: id.into(), name: name.into(), from, data: airband_core::audio::base64_encode(&buf), done, total: with_total.then_some(total) })
        };
        // a part lost on a bad connection is sent again, to the same place, a few times before giving up
        let send = |part: &airband_core::radio::AttachmentPart| -> Result<(u64, bool), RadioError> {
            let mut tries = 0;
            loop {
                match self.link.attachment_part(part) {
                    Ok(answer) => return Ok(answer),
                    Err(LinkError::Refused) => return Err(RadioError::Refused),
                    Err(_) if tries < 6 => {
                        tries += 1;
                        thread::sleep(Duration::from_secs(tries.min(4)));
                    }
                    // a file cannot be left with the relay: it needs his computer there to take it
                    Err(_) => return Err(RadioError::Offline),
                }
            }
        };
        let (_, any) = send(&part_at(0, true)?)?;
        let mut arrived = PART.min(total);
        if !sent(arrived, total) {
            return Err(RadioError::Refused);
        }
        if arrived >= total {
            return Ok(());
        }
        if !any {
            // one after another, each from where the tower says it has got to
            let mut from = arrived;
            loop {
                let part = part_at(from, false)?;
                let done = part.done;
                from = send(&part)?.0;
                if !sent(from, total) {
                    return Err(RadioError::Refused);
                }
                if done {
                    return Ok(());
                }
            }
        }
        let starts: Vec<u64> = (1..total.div_ceil(PART)).map(|k| k * PART).collect();
        let next = std::sync::atomic::AtomicUsize::new(0);
        let failed: Mutex<Option<RadioError>> = Mutex::new(None);
        let (tx, rx) = channel::<u64>();
        thread::scope(|scope| {
            for _ in 0..AT_ONCE.min(starts.len()) {
                let tx = tx.clone();
                let (next, failed, starts, part_at, send) = (&next, &failed, &starts, &part_at, &send);
                scope.spawn(move || {
                    while failed.lock().unwrap().is_none() {
                        let Some(from) = starts.get(next.fetch_add(1, Ordering::SeqCst)).copied() else { break };
                        match part_at(from, true).and_then(|part| send(&part).map(|_| part.data.len() as u64 * 3 / 4)) {
                            Ok(bytes) => {
                                let _ = tx.send(bytes);
                            }
                            Err(e) => *failed.lock().unwrap() = Some(e),
                        }
                    }
                });
            }
            drop(tx);
            // progress, as each part lands; he can take the file off while it goes
            for bytes in rx {
                arrived = (arrived + bytes).min(total);
                if !sent(arrived, total) {
                    *failed.lock().unwrap() = Some(RadioError::Refused);
                }
            }
        });
        match failed.into_inner().unwrap() {
            Some(e) => Err(e),
            None => Ok(()),
        }
    }
}
