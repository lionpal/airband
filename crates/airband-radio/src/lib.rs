//! The radio: everything a phone app does except making sound, hearing it and drawing.
//!
//! Where things are:
//! - this file: what a host implements, the statuses and errors it is given, and the types every part shares
//! - `radio`: one paired computer, and everything a host can ask of it
//! - `chat`, `accounts`: what crosses to the host for the chat and for the coding-tool accounts
//! - `link`: reaching the tower, directly or sealed through a relay
//! - `net`: `airband_io::http`, the one HTTP client, under a short name
//! - `desk`: every paired computer as one: the merged chat, what is waiting, where his messages go
//!   (`desk::fanout`: asking every computer the same thing at once)
//! - `call`: the call-mode loop
//! - `voice`: outbound, words said aloud by the voice he chose on this device
//! - `ears`: inbound, his speech to text, by the model or the service he chose on this device
//! - `outbox`: delivering typed messages over a bad connection
//! - `takes`: what he says, recorded from its first sample to its last and kept until his computer has it
//! - `store`: what is kept on the device; `kept`: a file of ours kept, and what happens when it is damaged
//! - `shared`: what the app and its notification extension both read, in the folder they share
//! - `session`: what his next words take with them (files he attached, the question they answer)
//! - `choices`: what he chooses to read, listen and speak with, and his keys for it (`keys`, `services`)
//! - `senses`: why what he chose cannot be used, worded in one place
//! - `mouth`, `voices`: the voice he chose, on the device or a service; `hears`, `ears_stream`: listening by
//!   one upload or live
//! - `models`, `engines`, `catalog`: the models that run on the device, what runs them, and the catalog
//! - `shared`: what the app and its notification extension both keep that is no secret
//!
//! A host (the iPhone app, in Swift, and the terminal host in the `airband` command) implements
//! [`RadioHost`]: speak this text, listen for a reply, show this status. The loop here decides everything
//! else: when to ask the tower for the next transmission, when to open the microphone, where a reply goes,
//! and what to do when the network drops. Swift and Kotlin get this API generated by UniFFI.
