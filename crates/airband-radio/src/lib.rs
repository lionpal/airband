/// A message he typed that is on its way.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize, uniffi::Record)]
pub struct Outgoing {
    pub id: String,
    pub text: String,
    /// The message it replies to, if he picked one.
    pub re: Option<String>,
    /// When he sent it, in milliseconds since 1970.
    pub at: u64,
    /// The room he was looking at when he sent it (`group:<name>`), if he was in one.
    #[serde(default)]
    pub scope: Option<String>,
    /// For a quick message: the words on the button. `text` is then the whole instruction.
    #[serde(default)]
    pub label: Option<String>,
    /// Files that go with it, by the ids they reached the tower under.
    #[serde(default)]
    pub attachments: Vec<String>,
    /// For the tower, not for a host to read: the agents on his screen that other computers have, as JSON.
    #[serde(default)]
    pub others: String,
}

fn chat(m: airband_core::radio::Message) -> ChatMessage {
    use airband_core::routing::shown;
    ChatMessage { seq: m.seq, id: m.id, at: m.at, from: shown(&m.from), group: m.group, to: m.to.iter().map(|t| shown(t)).collect(), needs_you: m.kind == Some(Kind::NeedsYou), fyi: m.kind == Some(Kind::Fyi) || m.cancelled, stalled: m.kind == Some(Kind::Stalled), text: m.text, long: m.long, queued: m.queued, seen: m.seen.unwrap_or(0), options: m.options, recommended: m.recommended, permission: m.permission, pictures: m.pictures.into_iter().map(|p| ChatPicture { id: p.id, width: p.width, height: p.height }).collect(), links: m.links, agent: m.agent, station: String::new(), open: m.open, badge: String::new(), colour: 0, read: m.read }
}

fn chat_feed(feed: Feed) -> ChatFeed {
    ChatFeed {
        seq: feed.seq,
        messages: feed.messages.into_iter().map(chat).collect(),
        agents: feed.roster.into_iter().map(|r| ChatAgent { id: r.id, callsign: airband_core::routing::shown(&r.callsign), group: r.group, harness: r.harness, waiting: r.waiting, reachable: r.reachable, state: r.state, subagents: r.subagents, doing: r.doing, held: r.held, model: r.model, effort: r.effort }).collect(),
        quick: feed.quick.into_iter().map(|q| QuickMessage { label: q.label, text: q.text }).collect(),
        projects: feed.projects,
        colours: feed.colours.into_iter().collect(),
        open: feed.open,
        station: feed.station,
    }
}

#[derive(Debug, uniffi::Error)]
pub enum RadioError {
    BadLink { reason: String },
    /// Nothing came back: no network, no relay, or the tower is not running.
    Offline,
    /// The tower answered and said no.
    Refused,
    /// The tower answered, said no, and said why in words for him.
    Told { reason: String },
}

impl std::fmt::Display for RadioError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            RadioError::BadLink { reason } => write!(f, "{reason}"),
            RadioError::Offline => write!(f, "cannot reach the tower"),
            RadioError::Refused => write!(f, "the tower refused that"),
            RadioError::Told { reason } => write!(f, "{reason}"),
        }
    }
}

impl From<LinkError> for RadioError {
    fn from(e: LinkError) -> Self {
        match e {
            LinkError::Offline | LinkError::Away | LinkError::Behind => RadioError::Offline,
            LinkError::Refused => RadioError::Refused,
        }
    }
}

/// One line of the chat: something an agent said, cut to a line or two, or something he said.
#[derive(Debug, Clone, uniffi::Record)]
pub struct ChatMessage {
    pub seq: u64,
    pub id: String,
    /// Milliseconds since 1970.
    pub at: u64,
    /// A callsign, or "you".
    pub from: String,
    pub group: String,
    /// For his messages: who it went to.
    pub to: Vec<String>,
    /// The agent is stopped until he answers or acts.
    pub needs_you: bool,
    /// Not worth his attention: show it dimmed or folded away.
    pub fyi: bool,
    /// The agent stopped here without finishing or asking: it needs a poke.
    pub stalled: bool,
    pub text: String,
    /// There is more than `text` says; `more(id)` has it.
    pub long: bool,
    /// His own words, waiting for the agent to stop what it is doing. He can still take them back.
    pub queued: bool,
    /// For his own words: when the agent took them in, in milliseconds since 1970; 0 while that is not known.
    pub seen: u64,
    /// Answers he can give with one tap: show each as a button and send the one tapped with `re` set to this message.
    pub options: Vec<String>,
    /// Which of `options` the agent itself recommended, if it said. Mark only that one; with none, mark none.
    pub recommended: Option<u32>,
    /// A request for permission to do one thing on his computer. Offer its two answers and his own words, and
    /// never a "do what you think best".
    pub permission: bool,
    /// Pictures that go with it, the ones the agent meant him to see first. `picture(id)` fetches one.
    pub pictures: Vec<ChatPicture>,
    /// Web links the agent wrote (an artifact, a pull request). The short text leaves them out: show them to open.
    pub links: Vec<String>,
    /// The agent that said it: stable while that agent runs, whatever it is called. Nothing for his own messages.
    pub agent: Option<String>,
    /// Which computer it came from, when he is paired with several and a [`Desk`] merged them. Empty otherwise.
    pub station: String,
    /// It needs him and nothing has answered it yet. An inbox shows these.
    pub open: bool,
    /// Two characters for who said it ("S3", "CP"), and its team's place in the host's list of team colours.
    /// A [`Desk`] fills these in; empty and 0 otherwise, and always for his own messages.
    pub badge: String,
    pub colour: u8,
    /// It holds something to read whole, called this ("the refund email"): offer the full message under that
    /// name. [`Desk::full`] fetches it.
    pub read: Option<String>,
}

