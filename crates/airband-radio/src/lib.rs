//! The radio: everything a phone app does except making sound, hearing it and drawing.
//!
//! Where things are:
//! - this file: the API a host sees (what it implements, what it can call) and the types that cross to Swift and Kotlin
//! - `link`: reaching the tower, directly or sealed through a relay
//! - `net`: the HTTP agent, which can find a host the local network's DNS has wrong
//! - `desk`: every paired computer as one: the merged chat, what is waiting, where his messages go
//! - `call`: the call-mode loop
//! - `voice`: outbound, the tower's speech fetched in parts and handed to the host as PCM
//! - `ears`: inbound, his speech to text, by the host's own recognition or a service (the tower says which)
//! - `outbox`: delivering typed messages over a bad connection
//! - `store`: what is kept on the device
//!
//! A host (Swift on iPhone and Mac, Kotlin on Android, the terminal host in the `airband` command) implements
//! [`RadioHost`]: speak this text, listen for a reply, show this status. The loop here decides everything
//! else: when to ask the tower for the next transmission, when to open the microphone, where a reply goes,
//! and what to do when the network drops. Swift and Kotlin get this API generated by UniFFI.
